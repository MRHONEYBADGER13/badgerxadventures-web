@app.route("/api/redeem", methods=["POST"])
def api_redeem():
    data = request.get_json(force=True) or {}
    code = (data.get("code") or "").strip().upper()
    email = (data.get("email") or "").strip().lower()
    password = data.get("password") or ""
    if not code or not email or len(password) < 8:
        return jsonify({"error": "Enter your code, an email, and a password (8+ characters)."}), 400

    conn = get_db()
    row = conn.execute("SELECT * FROM invite_codes WHERE code = ?", (code,)).fetchone()
    if not row:
        return jsonify({"error": "That code isn't recognized."}), 404
    if row["status"] != "unused":
        return jsonify({"error": "That code has already been used."}), 409
    if conn.execute("SELECT 1 FROM owners WHERE email = ?", (email,)).fetchone():
        return jsonify({"error": "That email already has an account."}), 409

    pw_hash = auth.hash_password(password)
    cur = conn.execute(
        "INSERT INTO owners (code_id, email, password_hash) VALUES (?, ?, ?)",
        (row["id"], email, pw_hash),
    )
    owner_id = cur.lastrowid
    conn.execute(
        "UPDATE invite_codes SET status = 'claimed', claimed_at = datetime('now') WHERE id = ?",
        (row["id"],),
    )
    conn.commit()

    resp = jsonify({"ok": True, "pin_type": row["pin_type"]})
    token = auth.make_owner_token(owner_id)
    resp.set_cookie("owner_session", token, httponly=True, samesite="Lax", max_age=60 * 60 * 24 * 30)
    return resp


