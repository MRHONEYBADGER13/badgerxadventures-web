# ---------- request helpers ----------

def get_db():
    if "db" not in g:
        g.db = db.get_db()
    return g.db


@app.teardown_appcontext
def close_db(exc):
    d = g.pop("db", None)
    if d is not None:
        d.close()


def current_owner_id():
    token = request.cookies.get("owner_session")
    if not token:
        return None
    return auth.read_owner_token(token)


def current_admin_id():
    token = request.cookies.get("admin_session")
    if not token:
        return None
    return auth.read_admin_token(token)


def owner_required(fn):
    @wraps(fn)
    def wrapper(*a, **kw):
        oid = current_owner_id()
        if not oid:
            return jsonify({"error": "not logged in"}), 401
        g.owner_id = oid
        return fn(*a, **kw)
    return wrapper


def admin_required(fn):
    @wraps(fn)
    def wrapper(*a, **kw):
        aid = current_admin_id()
        if not aid:
            return jsonify({"error": "admin login required"}), 401
        g.admin_id = aid
        return fn(*a, **kw)
    return wrapper


def pin_to_json(row):
    d = dict(row)
    d["photos"] = json.loads(d.get("photos") or "[]")
    d["availability"] = json.loads(d.get("availability") or "[]")
    return d


