def owner_required(fn):
    @wraps(fn)
    def wrapper(*a, **kw):
        oid = current_owner_id()
        if not oid:
            return jsonify({"error": "not logged in"}), 401
        g.owner_id = oid
        return fn(*a, **kw)
    return wrapper


def admin_required(fn):
    @wraps(fn)
    def wrapper(*a, **kw):
        aid = current_admin_id()
        if not aid:
            return jsonify({"error": "admin login required"}), 401
        g.admin_id = aid
        return fn(*a, **kw)
    return wrapper


def current_cleaner_id():
    token = request.cookies.get("cleaner_session")
    if not token:
        return None
