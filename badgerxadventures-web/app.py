    photos.remove(path)
    conn.execute("UPDATE pins SET photos = ?, updated_at = datetime('now') WHERE id = ?",
                 (json.dumps(photos), pin["id"]))
    conn.commit()
    fname = os.path.basename(path)
    fpath = os.path.join(UPLOAD_DIR, fname)
    if os.path.exists(fpath):
        os.remove(fpath)
    return photos, None


