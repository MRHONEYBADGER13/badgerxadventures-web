def _client_ip():
    # Render sits behind a proxy -- the real visitor IP is the first hop in
    # X-Forwarded-For when it's present, falling back to the direct address.
    fwd = request.headers.get("X-Forwarded-For", "")
    if fwd:
        return fwd.split(",")[0].strip()
    return request.remote_addr or ""


def record_visit():
    """Counts a unique visitor once per UTC calendar day, for the admin
    dashboard's visitor counters. Only the main map page calls this -- never
    admin or API routes -- and only a salted hash of the visitor's IP is
    ever stored, never the IP itself."""
    ip = _client_ip()
    if not ip:
        return
    ip_hash = hashlib.sha256((VISIT_SALT + ip).encode("utf-8")).hexdigest()
    day = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    conn = get_db()
    conn.execute(
        "INSERT OR IGNORE INTO site_visits (day, ip_hash) VALUES (?, ?)",
        (day, ip_hash),
    )
    conn.commit()


def record_visitor_log(path):
    """A rolling 24-hour log of real page views -- unlike record_visit
    above, which only ever stores a hashed IP for the counter, this keeps
    the real address so the admin's Visitors panel can show who's actually
    on the site and ban anyone unwanted. Every insert also sweeps out
    anything older than a day, so nothing here is ever kept longer than
    that."""
    ip = _client_ip()
    if not ip:
        return
    conn = get_db()
    conn.execute(
        "INSERT INTO visitor_log (ip, path, created_at) VALUES (?, ?, datetime('now'))",
        (ip, path),
    )
    conn.execute("DELETE FROM visitor_log WHERE created_at < datetime('now', '-1 day')")
    conn.commit()


