    conn.execute(
        "INSERT INTO banned_ips (ip, label) VALUES (?, ?) "
        "ON CONFLICT(ip) DO UPDATE SET label = excluded.label",
        (ip, display_name),
    )
    conn.commit()
    return jsonify({"ok": True, "ip": ip})

