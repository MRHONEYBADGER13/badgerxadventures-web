def _client_ip():
    # Render sits behind a proxy -- the real visitor IP is the first hop in
    # X-Forwarded-For when it's present, falling back to the direct address.
    fwd = request.headers.get("X-Forwarded-For", "")
    if fwd:
        return fwd.split(",")[0].strip()
    return request.remote_addr or ""


def record_visit():
    """Counts a unique visitor once per UTC calendar day, for the admin
    dashboard's visitor counters. Only the main map page calls this -- never
    admin or API routes -- and only a salted hash of the visitor's IP is
    ever stored, never the IP itself."""
    ip = _client_ip()
    if not ip:
        return
    ip_hash = hashlib.sha256((VISIT_SALT + ip).encode("utf-8")).hexdigest()
    day = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    conn = get_db()
    conn.execute(
        "INSERT OR IGNORE INTO site_visits (day, ip_hash) VALUES (?, ?)",
        (day, ip_hash),
    )
    conn.commit()


# A permanently banned IP is blocked from the whole site -- everywhere
# except the admin dashboard itself (so an admin can never lock themselves
# out) and static assets. This is separate from -- and stronger than -- a
# Lake Chat ban: it survives the person clearing cookies for a fresh
# session, since it's keyed on their IP instead.
_IP_BAN_EXEMPT_PREFIXES = ("/admin", "/api/admin", "/static")

_IP_BLOCKED_PAGE = (
    "<!doctype html><html><body style=\"font-family:sans-serif;padding:40px;"
    "text-align:center;color:#4A7282\"><h2>Access blocked</h2>"
    "<p>This device has been blocked from BADGERxADVENTURES.</p></body></html>"
)


@app.before_request
def _enforce_ip_ban():
    if request.path.startswith(_IP_BAN_EXEMPT_PREFIXES):
        return None
    ip = _client_ip()
    if not ip:
        return None
    banned = get_db().execute("SELECT 1 FROM banned_ips WHERE ip = ?", (ip,)).fetchone()
    if banned:
        return _IP_BLOCKED_PAGE, 403


