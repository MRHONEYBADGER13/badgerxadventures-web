CHAT_NAME_MAX = 24
CHAT_MSG_MAX = 500
CHAT_KICK_MINUTES = 5
CHAT_PING_REQUEST_MINUTES = 5   # how long an un-agreed ping@ request waits before it expires
CHAT_PING_REVEAL_MINUTES = 20   # how long a mutually-agreed location stays shown on the map

def chat_cleanup(conn):
    """Lazy expiry: run on every chat request instead of a separate worker.
    Messages vanish 5 hours after posting; a claimed guest name frees up 7
    days after being claimed; an admin kick lifts itself after
    CHAT_KICK_MINUTES unless an admin adds the person back sooner; a
    ping@ request or an agreed-to location reveal both clean up the same
    way, just against their own expires_at."""
    conn.execute("DELETE FROM chat_messages WHERE created_at < datetime('now', '-5 hours')")
    conn.execute("DELETE FROM chat_names WHERE expires_at < datetime('now')")
    conn.execute("DELETE FROM chat_bans WHERE expires_at IS NOT NULL AND expires_at < datetime('now')")
    conn.execute("DELETE FROM chat_locations WHERE updated_at < datetime('now', '-5 minutes')")
    conn.execute("DELETE FROM chat_pings WHERE expires_at < datetime('now')")
    conn.commit()

def current_chat_sid():
    return request.cookies.get("chat_sid")

def chat_is_banned(conn, session_id, owner_id):
    return chat_ban_row(conn, session_id, owner_id) is not None

def chat_ban_row(conn, session_id, owner_id):
    """The active ban row for this person, if any (None once it has
    expired -- chat_cleanup() deletes expired rows on every request)."""
    if owner_id:
        return conn.execute(
            "SELECT * FROM chat_bans WHERE owner_id = ? ORDER BY id DESC LIMIT 1", (owner_id,)
        ).fetchone()
    if session_id:
        return conn.execute(
            "SELECT * FROM chat_bans WHERE session_id = ? ORDER BY id DESC LIMIT 1", (session_id,)
        ).fetchone()
    return None

def chat_identity(conn):
    """Who is asking: the site admin always chats as a fixed "BADGER"
    identity (no claiming, never banned); a business/stay owner always
    chats as their pin's title (live, never stored separately); everyone
    else chats as whatever guest name their browser session has claimed,
    if any."""
    admin_id = current_admin_id()
    if admin_id:
        return {"name": "BADGER", "name_lower": "badger", "session_id": f"admin:{admin_id}",
                "owner_id": None, "kind": "admin", "banned": False}
    owner_id = current_owner_id()
    if owner_id:
        pin = conn.execute(
            "SELECT title FROM pins WHERE owner_id = ? AND pin_type IN ('business','stay')",
            (owner_id,),
        ).fetchone()
        if pin and (pin["title"] or "").strip():
            name = pin["title"].strip()
            return {"name": name, "name_lower": name.lower(), "session_id": None,
                    "owner_id": owner_id, "kind": "owner",
                    "banned": chat_is_banned(conn, None, owner_id)}
        return None
    sid = current_chat_sid()
    if not sid:
        return None
    row = conn.execute("SELECT * FROM chat_names WHERE session_id = ?", (sid,)).fetchone()
    if not row:
        return None
    return {"name": row["name"], "name_lower": row["name_lower"], "session_id": sid,
            "owner_id": None, "kind": "guest",
            "banned": chat_is_banned(conn, sid, None)}

def _chat_targets(conn):
    """Every name someone could currently be @mentioned by: active guest
    chat names, plus every live business/stay pin title."""
    names = set()
    for row in conn.execute("SELECT name FROM chat_names WHERE expires_at > datetime('now')"):
        names.add(row["name"])
    for row in conn.execute("SELECT title FROM pins WHERE pin_type IN ('business','stay')"):
        if row["title"]:
            names.add(row["title"])
    return names

def _chat_on_lake_names(conn):
    """name_lower of everyone currently reporting themselves as out on the
    lake right now -- guests via their claimed chat_names row, owners via
    their pin. A stale chat_locations row (chat_cleanup) just drops out of
    this join, so nothing needs to actively mark someone as "no longer"."""
    names = set()
    for row in conn.execute(
        "SELECT cn.name_lower FROM chat_locations cl "
        "JOIN chat_names cn ON cn.session_id = cl.session_id "
        "WHERE cl.session_id IS NOT NULL AND cl.on_lake = 1"
    ):
        names.add(row["name_lower"])
    for row in conn.execute(
        "SELECT lower(p.title) AS nl FROM chat_locations cl "
        "JOIN pins p ON p.owner_id = cl.owner_id AND p.pin_type IN ('business','stay') "
        "WHERE cl.owner_id IS NOT NULL AND cl.on_lake = 1"
    ):
        if row["nl"]:
            names.add(row["nl"])
    return names

def _find_mentions(text, targets):
    """Scan text for '@name' where name is a known chat target -- longest
    match first, so a multi-word business name wins over a shorter prefix
    of it, and a match must end at a word boundary."""
    found = set()
    lowered = text.lower()
    candidates = sorted(targets, key=len, reverse=True)
    i, n = 0, len(text)
    while i < n:
        if text[i] == "@":
            rest = lowered[i + 1:]
            for cand in candidates:
                cl = cand.lower()
                if cl and rest.startswith(cl):
                    after = i + 1 + len(cl)
                    nxt = text[after] if after < n else ""
                    if not (nxt.isalnum() or nxt == "_"):
                        found.add(cl)
                        i = after
                        break
            else:
                i += 1
        else:
            i += 1
    return sorted(found)

def _chat_resolve_ping_name(conn, raw):
    """Match the text right after 'ping@' against everyone currently
    nameable in chat -- an exact (case-insensitive) name first, then the
    longest known name the text starts with, so trailing words after the
    name (like a normal @mention) don't break the match. Returns the
    target's real-cased name, or None."""
    raw = (raw or "").strip()
    if not raw:
        return None
    low = raw.lower()
    targets = _chat_targets(conn)
    for t in targets:
        if t.lower() == low:
            return t
    for t in sorted(targets, key=len, reverse=True):
        tl = t.lower()
        if tl and low.startswith(tl):
            nxt = raw[len(tl):len(tl) + 1]
            if not (nxt.isalnum() or nxt == "_"):
                return t
    return None

def _chat_ping_side(row, identity):
    """Which side of a chat_pings row this identity is on -- 'from', 'to',
    or None if it's neither (matched the same way chat_identity() itself
    is: owner_id for owners, session_id for guests)."""
    if identity["owner_id"]:
        if row["from_owner_id"] == identity["owner_id"]:
            return "from"
        if row["to_owner_id"] == identity["owner_id"]:
            return "to"
    elif identity["session_id"]:
        if row["from_session_id"] == identity["session_id"]:
            return "from"
        if row["to_session_id"] == identity["session_id"]:
            return "to"
    return None

def _chat_ping_clear_for(conn, session_id, owner_id):
    """Only one active/pending ping@ request per person at a time -- drop
    anything else involving them (either side) before starting a fresh
    one, so the consent UI never has to juggle more than one."""
    if owner_id:
        conn.execute("DELETE FROM chat_pings WHERE from_owner_id = ? OR to_owner_id = ?", (owner_id, owner_id))
    elif session_id:
        conn.execute("DELETE FROM chat_pings WHERE from_session_id = ? OR to_session_id = ?", (session_id, session_id))

