"""BADGERxADVENTURES listings app.

Flask + SQLite. Public map shows every pin. A code, generated by the admin,
is the only way to create an owner account, and each code is good for
exactly one pin. Once placed, an owner can keep editing (but never delete)
their own pin's photos/phone/description/events/availability; only the
admin can edit or delete any pin.
"""
