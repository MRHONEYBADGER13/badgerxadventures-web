@app.route("/api/my-pin", methods=["POST"])
@owner_required
def api_my_pin_create():
    """Place the owner's one and only pin. Fails if they already have one.
    The location is set here and can never be changed again by the owner --
    only an admin edit can move a pin from here on."""
    conn = get_db()
    existing = conn.execute("SELECT 1 FROM pins WHERE owner_id = ?", (g.owner_id,)).fetchone()
    if existing:
        return jsonify({"error": "You've already placed your pin. Edit it instead."}), 409

    owner = conn.execute("SELECT c.pin_type FROM owners o JOIN invite_codes c ON c.id = o.code_id "
                          "WHERE o.id = ?", (g.owner_id,)).fetchone()
    pin_type = owner["pin_type"]
    data = request.get_json(force=True) or {}
    title = (data.get("title") or "").strip()
    xy = valid_xy(data.get("x"), data.get("y"))
    if not title or xy is None:
        return jsonify({"error": "A location on the map and a name are required."}), 400
    x, y = xy

    try:
        fields = fields_from_payload(pin_type, data)
    except ValueError as e:
        return jsonify({"error": str(e)}), 400
    fields["title"] = title

    cols = ["owner_id", "pin_type", "x", "y"] + list(fields.keys())
    placeholders = ", ".join("?" for _ in cols)
    values = [g.owner_id, pin_type, x, y] + list(fields.values())
    cur = conn.execute(
        f"INSERT INTO pins ({', '.join(cols)}) VALUES ({placeholders})", values
    )
    conn.commit()
    return jsonify({"ok": True, "id": cur.lastrowid})


@app.route("/api/my-pin", methods=["PUT"])
@owner_required
def api_my_pin_update():
    conn = get_db()
    pin = conn.execute("SELECT * FROM pins WHERE owner_id = ?", (g.owner_id,)).fetchone()
    if not pin:
        return jsonify({"error": "Place your pin first."}), 404
    data = request.get_json(force=True) or {}
    # x, y, and pin_type are never accepted here: an owner can edit their
    # pin's info and photos, but the location is fixed once placed, and only
    # an admin can move it or change what kind of pin it is.
    try:
        fields = fields_from_payload(pin["pin_type"], data)
    except ValueError as e:
        return jsonify({"error": str(e)}), 400
    if "title" in data:
        title = (data.get("title") or "").strip()
        if not title:
            return jsonify({"error": "A name is required."}), 400
        fields["title"] = title
    if not fields:
        return jsonify({"error": "Nothing to update."}), 400
    set_clause = ", ".join(f"{k} = ?" for k in fields)
    conn.execute(f"UPDATE pins SET {set_clause}, updated_at = datetime('now') WHERE owner_id = ?",
                 (*fields.values(), g.owner_id))
    conn.commit()
    return jsonify({"ok": True})


def _save_photo(file_storage):
    img = Image.open(file_storage.stream)
    img = ImageOps.exif_transpose(img)  # respect phone camera orientation, then drop the EXIF
    img = img.convert("RGB")
    img.thumbnail((1600, 1600))
    name = f"{uuid.uuid4().hex}.jpg"
    img.save(os.path.join(UPLOAD_DIR, name), "JPEG", quality=82)
    return f"/static/uploads/{name}"


def _add_photo(conn, pin, file):
    photos = json.loads(pin["photos"] or "[]")
    cap = MAX_PHOTOS_BY_TYPE.get(pin["pin_type"], 5)
    if len(photos) >= cap:
        return None, (jsonify({"error": f"Max {cap} photos."}), 400)
    if not file or not file.content_type.startswith("image/"):
        return None, (jsonify({"error": "Please upload an image file."}), 400)
    try:
        path = _save_photo(file)
    except Exception:
        return None, (jsonify({"error": "Couldn't read that image."}), 400)
    photos.append(path)
    conn.execute("UPDATE pins SET photos = ?, updated_at = datetime('now') WHERE id = ?",
                 (json.dumps(photos), pin["id"]))
    conn.commit()
    return photos, None


def _remove_photo(conn, pin, path):
    photos = json.loads(pin["photos"] or "[]")
    if path not in photos:
        return None, (jsonify({"error": "Photo not found."}), 404)
    photos.remove(path)
    conn.execute("UPDATE pins SET photos = ?, updated_at = datetime('now') WHERE id = ?",
                 (json.dumps(photos), pin["id"]))
    conn.commit()
    fname = os.path.basename(path)
    fpath = os.path.join(UPLOAD_DIR, fname)
    if os.path.exists(fpath):
        os.remove(fpath)
    return photos, None


